@pytest.mark.asyncio
async def test_http_400_schema_drift_envelope(broker: BrokerDaemon) -> None:
    """Upstream HTTP 400 Bad Request surfaces UPSTREAM_SCHEMA_DRIFT error code."""
    drift_error = {
        "ok": False,
        "error": {
            "code": UPSTREAM_SCHEMA_DRIFT,
            "message": "Upstream returned HTTP 400 Bad Request (schema drift detected).",
            "retryable": False,
        },
    }

    # Test 1: batchexecute schema drift on list_sources
    with patch.object(broker, "send_to_companion", new=AsyncMock(return_value=drift_error)):
        res = await broker.dispatch({"action": "list_sources", "notebook_id": "nb-phase5"})
        assert res["ok"] is False
        assert res["error"]["code"] == UPSTREAM_SCHEMA_DRIFT
        assert res["error"]["retryable"] is False

    # Test 2: batchexecute schema drift on add_source mutation
    with patch.object(broker, "send_to_companion", new=AsyncMock(return_value=drift_error)):
        res_mut = await broker.dispatch({
            "action": "add_source",
            "notebook_id": "nb-phase5",
            "idempotency_key": "drift-idemp-001",
            "source": {"type": "text", "text": "test content", "title": "Doc"},
        })
        assert res_mut["ok"] is False
        assert res_mut["error"]["code"] == UPSTREAM_SCHEMA_DRIFT
        # Journal must record REJECTED (schema error is non-retryable)
        entry = broker.journal.get("drift-idemp-001")
        assert entry is not None
        assert entry.state == MutationState.REJECTED

    # Test 3: streaming query schema drift
    with patch.object(broker, "send_to_companion", new=AsyncMock(return_value=drift_error)):
        res_query = await broker.dispatch({
            "action": "query_notebook",
            "notebook_id": "nb-phase5",
            "question": "What changed in the schema?",
            "request_key": "drift-query-001",
        })
        assert res_query["ok"] is False
        assert res_query["error"]["code"] == UPSTREAM_SCHEMA_DRIFT
        assert res_query["error"]["retryable"] is False
        entry_q = broker.journal.get("drift-query-001")
        assert entry_q is not None
        assert entry_q.state == MutationState.REJECTED


