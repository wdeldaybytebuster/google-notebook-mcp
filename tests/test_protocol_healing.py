# 1. P-01: Mid-Stream Error Delta Emission
# ---------------------------------------------------------------------------


def test_mid_stream_severance_emits_error_delta() -> None:
    """Feeding partial streaming chunk without done delimiter must emit error delta on finalize()."""
    parser = GenerateFreeFormStreamParser()

    # Feed initial text delta chunk without done sentinel
    events = parser.feed(b'[["Partial text generated by model"]]\n')
    assert len(events) == 1
    assert events[0] == {"type": "text_delta", "text": "Partial text generated by model"}

    # Abrupt mid-stream severance (transport dropped before Google emitted [null])
    final_events = parser.finalize()
    assert len(final_events) == 1
    assert final_events[0] == {
        "type": "error_delta",
        "error": {
            "code": "STREAM_SEVERED",
            "message": "Stream severed unexpectedly by upstream transport.",
            "retryable": True,
        },
    }


def test_clean_stream_termination_emits_no_error_delta() -> None:
    """Feeding complete stream with Google's done sentinel must emit empty finalize() list."""
    parser = GenerateFreeFormStreamParser()

    events = parser.feed(b'[["Full response text"]]\n')
    assert len(events) == 1
    assert events[0]["type"] == "text_delta"

    # Google sends clean done sentinel: [null]
    done_events = parser.feed(b"[null]\n")
    assert len(done_events) == 1
    assert done_events[0] == {"type": "done"}

    # Finalize should emit empty list since stream was terminated cleanly
    final_events = parser.finalize()
    assert final_events == []


