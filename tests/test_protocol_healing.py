# 2. Resilient Surrogate Pair & Astral Plane Unicode Decoding
# ---------------------------------------------------------------------------


def test_batchexecute_surrogate_pair_decoder() -> None:
    """Stream containing astral plane Unicode code units across chunk boundaries decodes cleanly."""
    # Test 1: BatchexecuteStreamDecoder with 4-byte UTF-8 emoji (🚀: \xf0\x9f\x9a\x80) and math (𝔸: \xf0\x9d\x94\xb8)
    inner_payload = json.dumps(["Launch: 🚀 mission with math 𝔸 = 𝔘𝔫𝔦𝔠𝔬𝔡𝔢"], ensure_ascii=False)
    frame = [["wrb.fr", "test_rpc", inner_payload, None, None, None, None, 1]]
    full_wire = b")]}'\n" + json.dumps(frame, ensure_ascii=False).encode("utf-8")

    # Split wire right in the middle of 🚀 (\xf0\x9f | \x9a\x80)
    rocket_byte_index = full_wire.find(b"\xf0\x9f\x9a\x80")
    assert rocket_byte_index != -1
    split_pos = rocket_byte_index + 2  # Split 4-byte UTF-8 sequence in half

    chunk1 = full_wire[:split_pos]
    chunk2 = full_wire[split_pos:]

    decoder = BatchexecuteStreamDecoder()
    res1 = decoder.feed(chunk1)
    assert res1 == [], "Chunk 1 is an incomplete frame and should yield no records"

    res2 = decoder.feed(chunk2)
    assert len(res2) == 1, "Chunk 2 completes the frame and should yield exactly 1 record"
    record = res2[0]
    assert record["rpc_id"] == "test_rpc"
    assert record["data"] == ["Launch: 🚀 mission with math 𝔸 = 𝔘𝔫𝔦𝔠𝔬𝔡𝔢"]
    assert "\ufffd" not in str(record["data"]), "String assembly must not corrupt Unicode code points"

    # Test 2: JSON-escaped UTF-16 surrogate pairs split across chunk boundaries (\ud83d | \ude80)
    surrogate_inner = json.dumps(["Surrogate emoji: 🚀 and math: 𝔸"], ensure_ascii=True)
    surrogate_frame = [["wrb.fr", "surrogate_rpc", surrogate_inner, None, None, None, None, 1]]
    raw_escaped_wire = b")]}'\n" + json.dumps(surrogate_frame).encode("utf-8")

    surrogate_pos = raw_escaped_wire.find(b"\\\\ud83d")
    assert surrogate_pos != -1
    split_surrogate = surrogate_pos + 7  # Split between \ud83d and \ude80

    dec2 = BatchexecuteStreamDecoder()
    s1 = dec2.feed(raw_escaped_wire[:split_surrogate])
    assert s1 == []
    s2 = dec2.feed(raw_escaped_wire[split_surrogate:])
    assert len(s2) == 1
    assert s2[0]["data"] == ["Surrogate emoji: 🚀 and math: 𝔸"]

    # Test 3: GenerateFreeFormStreamParser with UTF-8 byte boundary split
    parser = GenerateFreeFormStreamParser()
    line = json.dumps([["Model streaming 🚀 rocket in progress"]], ensure_ascii=False) + "\n"
    wire_line = line.encode("utf-8")
    split_line = wire_line.find(b"\xf0\x9f\x9a\x80") + 2

    p_res1 = parser.feed(wire_line[:split_line])
    p_res2 = parser.feed(wire_line[split_line:])

    all_parsed = p_res1 + p_res2
    assert len(all_parsed) == 1
    assert all_parsed[0] == {"type": "text_delta", "text": "Model streaming 🚀 rocket in progress"}
    assert "\ufffd" not in all_parsed[0]["text"]


