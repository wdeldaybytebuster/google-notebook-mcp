@pytest.mark.asyncio
async def test_heartbeat_ping_pong_recovery(broker: BrokerDaemon) -> None:
    """Verifies heartbeat ping dispatch, pong validation, and connection drop on timeout."""
    # 1. Successful heartbeat: companion responds with HEARTBEAT_PONG
    dummy_writer = MagicMock()
    dummy_writer.wait_closed = AsyncMock()
    broker._active_companion_writer = dummy_writer

    with patch.object(
        broker,
        "send_to_companion",
        new=AsyncMock(return_value={"ok": True, "command": "HEARTBEAT_PONG", "type": "pong"}),
    ) as mock_send:
        healthy = await broker._send_heartbeat_ping()
        assert healthy is True
        assert broker._active_companion_writer is dummy_writer
        mock_send.assert_called_once()
        assert mock_send.call_args[1]["command"] == "HEARTBEAT_PING"

    # 2. Dropped connection: companion fails to respond with pong within timeout
    with patch.object(
        broker,
        "send_to_companion",
        new=AsyncMock(side_effect=asyncio.TimeoutError("No pong received within 5s")),
    ):
        healthy_after_timeout = await broker._send_heartbeat_ping()
        assert healthy_after_timeout is False
        # Active writer must be dropped to trigger auto-reconnect
        assert broker._active_companion_writer is None


@pytest.mark.asyncio
async def test_heartbeat_ipc_auto_reconnect_loop(broker: BrokerDaemon, tmp_path: Path) -> None:
    """Full IPC socket test: verifies ping/pong over wire and auto-reconnect restoration."""
    # Start the broker IPC server
    await broker.start()

    try:
        # Connect companion client #1
        reader1, writer1 = await open_ipc_connection(broker.config.socket_path)

        # Companion #1 sends hello handshake
        hello_msg = json.dumps({"type": "hello"}).encode("utf-8")
        writer1.write(struct.pack(IPC_FRAME_FORMAT, len(hello_msg)) + hello_msg)
        await writer1.drain()

        # Read hello_ack
        len_bytes = await reader1.readexactly(4)
        (ack_len,) = struct.unpack(IPC_FRAME_FORMAT, len_bytes)
        ack_bytes = await reader1.readexactly(ack_len)
        ack = json.loads(ack_bytes.decode("utf-8"))
        assert ack["type"] == "hello_ack"
        assert broker._active_companion_writer is not None

        # Companion sends ping to broker, broker responds with pong
        ping_msg = json.dumps({"type": "ping", "requestId": "req-ping-123"}).encode("utf-8")
        writer1.write(struct.pack(IPC_FRAME_FORMAT, len(ping_msg)) + ping_msg)
        await writer1.drain()

        resp_len_bytes = await reader1.readexactly(4)
        (resp_len,) = struct.unpack(IPC_FRAME_FORMAT, resp_len_bytes)
        resp_payload = await reader1.readexactly(resp_len)
        pong_resp = json.loads(resp_payload.decode("utf-8"))
        assert pong_resp["ok"] is True
        assert pong_resp["command"] == "HEARTBEAT_PONG"
        assert pong_resp["type"] == "pong"
        assert pong_resp["requestId"] == "req-ping-123"

        # Simulate dropped port on client #1
        writer1.close()
        await writer1.wait_closed()

        # Allow broker loop to observe connection close
        await asyncio.sleep(0.05)

        # Companion client #2 reconnects (auto-reconnect)
        reader2, writer2 = await open_ipc_connection(broker.config.socket_path)
        writer2.write(struct.pack(IPC_FRAME_FORMAT, len(hello_msg)) + hello_msg)
        await writer2.drain()

        len_bytes2 = await reader2.readexactly(4)
        (ack_len2,) = struct.unpack(IPC_FRAME_FORMAT, len_bytes2)
        ack_bytes2 = await reader2.readexactly(ack_len2)
        ack2 = json.loads(ack_bytes2.decode("utf-8"))
        assert ack2["type"] == "hello_ack"

        # Verify bridge is restored with companion client #2
        assert broker._active_companion_writer is not None

        writer2.close()
        await writer2.wait_closed()

    finally:
        await broker.stop()


