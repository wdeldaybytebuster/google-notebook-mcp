# 5. M-09: Safe Request Body Inspection (Zero Stream Consumption)
# ---------------------------------------------------------------------------


def test_safe_request_body_inspection_m09() -> None:
    """Verifies that request body inspection never consumes stream bodies."""
    # Simulation of inspectRequestBodySafely logic in JS:
    def inspect_request_body_safely(body: Any) -> str | None:
        if isinstance(body, str):
            return body
        if isinstance(body, dict):
            # Simulation of URLSearchParams.toString()
            return "&".join(f"{k}={v}" for k, v in body.items())
        # Never touch ReadableStream, generator, or unconsumed stream
        return None

    # String body
    assert inspect_request_body_safely("f.req=[[[...]]]") == "f.req=[[[...]]]"

    # URLSearchParams / key-value body
    assert inspect_request_body_safely({"f.req": "data", "at": "csrf"}) == "f.req=data&at=csrf"

    # ReadableStream or stream object: returns None safely without consumption
    class MockReadableStream:
        def __init__(self) -> None:
            self.bodyUsed = False

        def getReader(self) -> Any:
            self.bodyUsed = True
            return self

    mock_stream = MockReadableStream()
    assert inspect_request_body_safely(mock_stream) is None
    assert mock_stream.bodyUsed is False, "Stream body MUST NOT be touched or read"
